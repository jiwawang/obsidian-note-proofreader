let current: Strings = en;

/** Picks the strings for an app language code (Obsidian's getLanguage()); called once on load. */
export function setLanguage(code: string) {
	current = code.toLowerCase().startsWith("zh") ? zh : en;
}

/** The strings for the current language. English until setLanguage is called. */
export function t(): Strings {
	return current;
}
